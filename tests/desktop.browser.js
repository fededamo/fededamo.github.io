// Run on a fresh desktop page with agent-browser eval --stdin.
(() => {
  const assert = (condition, message) => { if (!condition) throw Error(message); };
  const app = (id) => document.getElementById(id);
  const launch = (id) => document.querySelector(`.desktop-icons [data-open="${id}"]`).click();
  const action = (id, name) => app(id).querySelector(`[data-action="${name}"]`).click();
  const active = (id) => app(id).hasAttribute('data-active') && !app(id).hidden;
  const mobile = matchMedia('(max-width: 700px)').matches;
  assert(!mobile, 'Use phone.browser.js for the phone interface');
  assert(document.documentElement.hasAttribute('data-desktop-ready'), 'Desktop did not initialize');
  assert(active('benvenuto'), 'Welcome must be open initially');
  assert(!document.querySelector('[data-task="benvenuto"]'), 'Welcome must not clutter the taskbar');
  assert(!document.querySelector('[data-show-desktop]'), 'The taskbar must not contain a permanent computer button');
  assert([...document.querySelectorAll('h1')].filter((heading) => heading.getClientRects().length).length === 1, 'The desktop needs one visible primary heading');
  launch('progetti');
  launch('profilo');
  assert(active('profilo') && !app('progetti').hidden, 'Opening an app must preserve other windows');
  const bar = app('profilo').querySelector('[data-drag]');
  bar.focus();
  const before = app('profilo').getBoundingClientRect();
  bar.dispatchEvent(new KeyboardEvent('keydown', { key: 'ArrowRight', altKey: true, bubbles: true }));
  assert(app('profilo').getBoundingClientRect().x > before.x, 'Keyboard window movement failed');
  const grip = app('profilo').querySelector('[data-resize]');
  grip.focus();
  grip.dispatchEvent(new KeyboardEvent('keydown', { key: 'ArrowLeft', bubbles: true }));
  assert(app('profilo').getBoundingClientRect().width < before.width, 'Keyboard resizing failed');
  const width = app('profilo').getBoundingClientRect().width;
  action('profilo', 'maximize');
  assert(app('profilo').getBoundingClientRect().width === document.querySelector('.desktop').clientWidth, 'Maximize failed');
  action('profilo', 'maximize');
  assert(app('profilo').getBoundingClientRect().width === width, 'Restore lost window geometry');
  action('profilo', 'minimize');
  assert(app('profilo').hidden && !document.querySelector('[data-task="profilo"]').hidden, 'Minimize removed the task');
  document.querySelector('[data-task="profilo"]').click();
  assert(active('profilo'), 'Taskbar did not restore the window');
  action('profilo', 'close');
  assert(app('profilo').hidden && document.querySelector('[data-task="profilo"]').hidden, 'Close did not remove the task');
  assert(active('progetti'), 'Closing the active window did not focus the previous window');
  action('progetti', 'minimize');
  action('benvenuto', 'minimize');
  assert([...document.querySelectorAll('[data-window]')].every((window) => window.hidden), 'Minimizing the open windows must reveal the desktop');
  assert(!document.querySelector('.desktop-icons').inert, 'Desktop icons did not become available again');
  const start = document.querySelector('[data-start]');
  start.click();
  assert(!document.querySelector('#start-menu').hidden && start.getAttribute('aria-expanded') === 'true', 'Start menu did not open');
  document.activeElement.dispatchEvent(new KeyboardEvent('keydown', { key: 'ArrowDown', bubbles: true }));
  assert(document.activeElement.dataset.open === 'profilo', 'Start menu keyboard navigation failed');
  document.activeElement.click();
  assert(active('profilo') && document.querySelector('#start-menu').hidden, 'Start menu app launch failed');
  app('profilo').dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape', bubbles: true }));
  assert(app('profilo').hidden, 'Escape did not close the active window');
  launch('curriculum');
  assert(app('curriculum').querySelector('button[disabled]'), 'Missing CV should not expose a fake download');
  assert(document.documentElement.scrollWidth <= innerWidth, 'Page overflows horizontally');
  action('curriculum', 'close');
  launch('benvenuto');
  history.replaceState(null, '', location.pathname);
  return `PASS: desktop windows, focus, taskbar, Start, keyboard controls, unavailable CV, overflow`;
})();
